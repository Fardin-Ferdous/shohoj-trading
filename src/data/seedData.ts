function makeMonthly(base: number[]): MonthlyReturnPoint[] {
  const months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
  return base.map((val, idx) => ({ month: months[idx % 12], returnPercent: val }));
}

function makeEquity(start: number, steps: number[]): { label: string; ownEquity: number; managedEquity: number }[] {
  let own = start;
  let managed = start;
  return steps.map((pct, idx) => {
    own = Math.round(own * (1 + pct / 100));
    managed = Math.round(managed * (1 + (pct * 0.92) / 100));
    return { label: `M${idx + 1}`, ownEquity: own, managedEquity: managed };
  });
}

